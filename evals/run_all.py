"""One command that regenerates every Part B number and the results table.

    python -m evals.run_all              # run everything, then build evals/results/RESULTS.md
    python -m evals.run_all --table-only # rebuild RESULTS.md from the JSON already in evals/results/

Every number in the report and README must come from a file this script writes (CI checks it).
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys

from evals.runners.rag_eval import RESULTS, ROOT

VARIANTS = ["v0_naive", "v1_decompose", "v2_hybrid", "v3_rerank", "v4_outcome", "v5_multivector", "v8_corrective",
            "best"]


def run(*args: str) -> None:
    print("$", " ".join(args), flush=True)
    subprocess.run([sys.executable, "-m", *args], cwd=ROOT, check=True)


def load(name: str) -> dict:
    p = RESULTS / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else {"results": {}, "meta": {}}


def build_table() -> str:
    ret, out, abl = load("retrieval"), load("outcomes"), load("ablation")
    judge = json.loads((RESULTS / "judge_calibration.json").read_text()) if (RESULTS / "judge_calibration.json").exists() else {}
    model = out["meta"].get("model_profile", "?")
    L = ["# GigBid results", "",
         f"Generated by `python -m evals.run_all`. Writer/critic model: **{model}**. "
         "Dataset: stand-in starter kit (see docs/DATA_CARD.md).", "",
         "## B5 results table", "",
         "| Variant | Evidence Recall@5 | nDCG@10 | Unsupported claims per proposal | Judge score | GigSim reply rate | "
         "p95 latency (s) | Cost per proposal (USD) |", "|---|---|---|---|---|---|---|---|"]
    for v in VARIANTS:
        r = ret["results"].get(v, {}).get("overall")
        o = out["results"].get(v, {}).get("overall")
        if not r and not o:
            continue
        cell = lambda d, k, f: (f.format(d[k]) if d and k in d else "-")  # noqa: E731
        L.append(f"| {'**best (shipped)**' if v == 'best' else v} | {cell(r, 'recall@5', '{:.3f}')} | "
                 f"{cell(r, 'ndcg@10', '{:.3f}')} | {cell(o, 'unsupported_claims_per_proposal_before', '{:.2f}')} | "
                 f"{cell(o, 'rubric_score', '{:.3f}')}* | {cell(o, 'reply_rate', '{:.3f}')} | "
                 f"{cell(o, 'p95_s', '{:.2f}')} | {cell(o, 'usd_per_proposal', '{:.4f}')} |")
    L += ["", "*Judge score: the Critic's rule rubric (0-1) until the LLM judge is calibrated. "
          + (f"Calibration so far: {json.dumps(judge)}." if judge else "Calibration pending: 30 human labels needed "
             "(evals/judge/labels.csv)."), ""]
    for name in ("retrieval_table", "ablation_table", "decisions_table", "injection_table"):
        p = RESULTS / f"{name}.md"
        if p.exists():
            L += [p.read_text().strip(), ""]
    if ret["meta"].get("hypothesis"):
        r = ret["results"]
        v0 = r.get("v0_naive", {}).get("overall", {}).get("recall@5 (4+ req)")
        v1 = r.get("v1_decompose", {}).get("overall", {}).get("recall@5 (4+ req)")
        v2 = r.get("v2_hybrid", {}).get("overall", {}).get("recall@5 (4+ req)")
        b = r.get("best", {}).get("overall", {}).get("recall@5 (4+ req)")
        hb = abl["results"].get("H-B test: V0 + decomposition + hybrid", {}).get("overall", {}).get("recall@5 (4+ req)")
        if None not in (v0, v1, v2, b):
            hb_txt = f" The exact hypothesis configuration (V0 + decomposition + hybrid) scores {hb:.3f} "                      f"({(hb - v0) * 100:+.1f} points): **{'supported' if hb - v0 >= 0.15 else 'rejected'}**."                 if hb is not None else ""
            L += ["## Hypothesis", "", ret["meta"]["hypothesis"], "",
                  f"Result on jobs with 4+ requirements: V0 {v0:.3f}, V1 (decomposition) {v1:.3f}, V2 (hybrid) {v2:.3f}, "
                  f"best {b:.3f} ({(b - v0) * 100:+.1f} points vs V0).{hb_txt} See docs/adr/0003-retrieval-choice.md.", ""]
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--table-only", action="store_true")
    a = ap.parse_args()
    if not a.table_only:
        run("evals.runners.rag_eval")
        run("evals.runners.ablation")
        run("evals.runners.decision_eval", "--variants", "best", "v8_corrective", "keyword")
        run("evals.runners.gigsim_outcomes", "--variants", *VARIANTS, "keyword")
        run("evals.runners.injection_eval")
    md = build_table()
    (RESULTS / "RESULTS.md").write_text(md + "\n", encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
