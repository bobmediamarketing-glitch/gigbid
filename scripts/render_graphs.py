"""Render both LangGraph graphs from code into docs/GRAPHS.md (Mermaid, renders on GitHub).

    python scripts/render_graphs.py

The diagrams are generated from the compiled graphs, so they cannot drift from the code.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from agent.graphs import bid_graph, conversation_graph  # noqa: E402


def main() -> None:
    out = ["# GigBid graphs", "", "Generated by `python scripts/render_graphs.py` from the compiled graphs. "
           "Dashed edges are conditional; every node can also route a halted run to `__end__`.", ""]
    for title, mod in [("Bid graph (one thread per job)", bid_graph),
                       ("Conversation graph (one thread per client conversation)", conversation_graph)]:
        mermaid = mod.compile().get_graph().draw_mermaid()
        out += [f"## {title}", "", f"Source: `{mod.__name__.replace('.', '/')}.py`", "", "```mermaid", mermaid.strip(),
                "```", ""]
    (ROOT / "docs" / "GRAPHS.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/GRAPHS.md")


if __name__ == "__main__":
    main()
