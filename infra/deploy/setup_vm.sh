#!/usr/bin/env bash
# One-command GigBid deployment on a fresh Ubuntu 22.04 / 24.04 VM (x86_64 or ARM64, 4 GB RAM or more).
#
#   git clone https://github.com/bobmediamarketing-glitch/gigbid.git && cd gigbid
#   GROQ_API_KEY=... bash infra/deploy/setup_vm.sh
#
# Optional environment variables:
#   DOMAIN              your domain pointing at this VM; default <public-ip>.sslip.io (free, works immediately)
#   GROQ_API_KEY        model key for the open profile (without it GigBid runs in rule mode)
#   REVIEWER_EMAIL      reviewer login; default reviewer@gigbid.example.com
#   REVIEWER_PASSWORD   default: generated (shown once at the end, also kept in infra/.env)
#   LANGFUSE_PUBLIC_KEY / LANGFUSE_SECRET_KEY / LANGFUSE_HOST   tracing
#
# Safe to re-run: it pulls the latest code, keeps existing secrets and restarts the stack.
set -euo pipefail

cd "$(dirname "$0")/../.."
ROOT=$(pwd)
ENV_FILE="$ROOT/infra/.env"
COMPOSE=(docker compose -f "$ROOT/infra/docker-compose.yml" --profile tls)

log() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }

# ---------------------------------------------------------------- 1. Docker (Ubuntu packages, no piped installers)
if ! command -v docker >/dev/null 2>&1 || ! docker compose version >/dev/null 2>&1; then
  log "Installing Docker"
  sudo apt-get update -y
  sudo apt-get install -y docker.io docker-compose-v2 git curl openssl
  sudo systemctl enable --now docker
  sudo usermod -aG docker "$USER" || true
fi
DOCKER_PREFIX=""
docker info >/dev/null 2>&1 || DOCKER_PREFIX="sudo"
COMPOSE=($DOCKER_PREFIX "${COMPOSE[@]}")

# ---------------------------------------------------------------- 2. Firewall: open 80/443 on the VM itself
# (Oracle Cloud's Ubuntu images ship iptables rules that drop everything but SSH; ufw users get a rule too.)
log "Opening ports 80 and 443 on the VM firewall"
for port in 80 443; do
  if sudo iptables -C INPUT -p tcp --dport "$port" -j ACCEPT 2>/dev/null; then :; else
    sudo iptables -I INPUT 1 -p tcp --dport "$port" -m state --state NEW -j ACCEPT || true
  fi
done
if command -v netfilter-persistent >/dev/null 2>&1; then sudo netfilter-persistent save || true; fi
if command -v ufw >/dev/null 2>&1 && sudo ufw status | grep -q active; then sudo ufw allow 80,443/tcp || true; fi

# ---------------------------------------------------------------- 3. Latest code
if [ -d .git ]; then
  log "Updating code"
  git pull --ff-only || true
fi

# ---------------------------------------------------------------- 4. Secrets (generated once, kept on re-runs)
rand() { openssl rand -hex 24; }
fernet() { openssl rand -base64 32 | tr '+/' '-_'; }
if [ ! -f "$ENV_FILE" ]; then
  log "Generating secrets in infra/.env"
  PUBLIC_IP=$(curl -fsS https://api.ipify.org || hostname -I | awk '{print $1}')
  DOMAIN=${DOMAIN:-${PUBLIC_IP}.sslip.io}
  REVIEWER_EMAIL=${REVIEWER_EMAIL:-reviewer@gigbid.example.com}
  REVIEWER_PASSWORD=${REVIEWER_PASSWORD:-$(openssl rand -base64 18 | tr -d '/+=' | cut -c1-20)}
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by infra/deploy/setup_vm.sh on $(date -u +%F). Never commit this file.
GIGBID_ENV=production
DOMAIN=$DOMAIN
WEB_BIND=127.0.0.1
GIGBID_ALLOW_SIGNUP=0
JWT_SECRET=$(rand)
TOKEN_ENCRYPTION_KEY=$(fernet)
MCP_CALLER_SECRET=$(rand)
POSTGRES_PASSWORD=$(rand)
GIGSIM_ADMIN_TOKEN=$(rand)
GIGSIM_ERROR_RATE=0.02
GIGBID_MODEL_PROFILE=open
GROQ_API_KEY=${GROQ_API_KEY:-}
LANGFUSE_HOST=${LANGFUSE_HOST:-}
LANGFUSE_PUBLIC_KEY=${LANGFUSE_PUBLIC_KEY:-}
LANGFUSE_SECRET_KEY=${LANGFUSE_SECRET_KEY:-}
REVIEWER_EMAIL=$REVIEWER_EMAIL
REVIEWER_PASSWORD=$REVIEWER_PASSWORD
EOF
  chmod 600 "$ENV_FILE"
else
  log "Keeping existing secrets in infra/.env"
  # allow adding a model key on a re-run without editing the file
  if [ -n "${GROQ_API_KEY:-}" ]; then sed -i "s|^GROQ_API_KEY=.*|GROQ_API_KEY=$GROQ_API_KEY|" "$ENV_FILE"; fi
fi
set -a; . "$ENV_FILE"; set +a

# ---------------------------------------------------------------- 5. Start everything
log "Building and starting the stack (first build takes a few minutes)"
"${COMPOSE[@]}" up -d --build

log "Waiting for the API"
for i in $(seq 1 90); do
  if "${COMPOSE[@]}" exec -T api python -c "import urllib.request,sys; sys.exit(0 if urllib.request.urlopen('http://127.0.0.1:8000/api/ping').status==200 else 1)" 2>/dev/null; then
    break
  fi
  sleep 4
done

# ---------------------------------------------------------------- 6. Reviewer account, preloaded with a persona
log "Creating the reviewer account (persona: Sara Malik, AI/ML)"
"${COMPOSE[@]}" exec -T api python -m apps.api.seed_reviewer --persona ai_ml --analyse 6

cat <<EOF

GigBid is up:   https://$DOMAIN
(HTTPS certificates are issued on the first visit; give it a minute if the browser warns at first.)

Reviewer login, for the PRIVATE Google Classroom comment only:
  email:    $REVIEWER_EMAIL
  password: $REVIEWER_PASSWORD
(kept in infra/.env, readable only by this user)

Logs:     ${COMPOSE[*]} logs -f api worker
Update:   git pull && bash infra/deploy/setup_vm.sh
EOF
